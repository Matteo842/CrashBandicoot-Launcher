"""Compile the Vulkan GLSL shaders to SPIR-V and embed them in C#.

Usage:  python tools/vulkan/build_shaders.py

Needs glslc: taken from GLSLC, PATH, or the Android NDK
(%LOCALAPPDATA%/Android/Sdk/ndk/<version>/shader-tools/<host>/glslc).
Writes RecompOne.Runtime/Gpu/Hle/Vk/VkShaderCode.g.cs; commit that file so
normal builds never need glslc.
"""
import base64
import glob
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "RecompOne.Runtime", "Gpu", "Hle", "Vk", "Shaders")
OUT = os.path.join(ROOT, "RecompOne.Runtime", "Gpu", "Hle", "Vk", "VkShaderCode.g.cs")

SHADERS = [
    ("PrimVert", "prim.vert"),
    ("PrimFrag", "prim.frag"),
    ("FullscreenVert", "fullscreen.vert"),
    ("PresentFrag", "present.frag"),
    ("Present24Frag", "present24.frag"),
    ("ImGuiVert", "imgui.vert"),
    ("ImGuiFrag", "imgui.frag"),
    ("CrtVert", "crt.vert"),
    ("CrtFrag", "crt.frag"),
    ("CrtDownFrag", "crt_down.frag"),
    ("CrtBlurFrag", "crt_blur.frag"),
]


def find_glslc():
    env = os.environ.get("GLSLC")
    if env and os.path.isfile(env):
        return env
    found = shutil.which("glslc")
    if found:
        return found
    roots = [
        os.path.join(os.environ.get("LOCALAPPDATA", ""), "Android", "Sdk", "ndk"),
        os.path.join(os.environ.get("ANDROID_HOME", ""), "ndk"),
        os.path.join(os.path.expanduser("~"), "Android", "Sdk", "ndk"),
    ]
    for root in roots:
        hits = sorted(glob.glob(os.path.join(root, "*", "shader-tools", "*", "glslc*")))
        if hits:
            return hits[-1]
    sys.exit("glslc not found: set GLSLC or install the Android NDK / Vulkan SDK")


def main():
    glslc = find_glslc()
    blobs = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, file in SHADERS:
            out = os.path.join(tmp, file + ".spv")
            # Vulkan 1.0 target: the Android minimum (API 26) may not have 1.1.
            subprocess.run([glslc, "--target-env=vulkan1.0", "-O", "-o", out,
                            os.path.join(SRC, file)], check=True)
            with open(out, "rb") as f:
                blobs.append((name, file, f.read()))

    lines = [
        "// <auto-generated> by tools/vulkan/build_shaders.py from Gpu/Hle/Vk/Shaders.",
        "// Do not edit: change the .vert/.frag source and rerun the script.",
        "namespace RecompOne.Runtime.Hle.Vulkan;",
        "",
        "internal static class VkShaderCode",
        "{",
    ]
    for name, file, data in blobs:
        lines.append(f"    // {file}, {len(data)} bytes")
        lines.append(f"    public const string {name} =")
        text = base64.b64encode(data).decode("ascii")
        chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
        for i, chunk in enumerate(chunks):
            end = ";" if i == len(chunks) - 1 else " +"
            lines.append(f'        "{chunk}"{end}')
        lines.append("")
    lines[-1] = "}"
    lines.append("")
    with open(OUT, "w", newline="\n", encoding="ascii") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({len(blobs)} shaders) with {glslc}")


if __name__ == "__main__":
    main()
